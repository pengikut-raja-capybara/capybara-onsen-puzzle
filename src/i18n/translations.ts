export function getChapterText(chapterId: number, fallbackTitle: string, fallbackSubtitle: string, lang: Language): { title: string; subtitle: string } {
  if (lang === "en" && CHAPTER_EN[chapterId]) {
    return CHAPTER_EN[chapterId];
  }
  return { title: fallbackTitle, subtitle: fallbackSubtitle };
}

export function getLevelTitle(levelId: string, fallbackTitle: string, lang: Language): string {
  if (lang === "en" && LEVEL_TITLES_EN[levelId]) {
    return LEVEL_TITLES_EN[levelId];
  }
  return fallbackTitle;
}

export function getLevelHint(levelId: string, fallbackHint: string | undefined, lang: Language): string | undefined {
  if (!fallbackHint) return undefined;
  if (lang === "en" && LEVEL_HINTS_EN[levelId]) {
    return LEVEL_HINTS_EN[levelId];
  }
  return fallbackHint;
}
