export type Language = "id" | "en";

export function getDefaultLanguage(): Language {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale || "";
    if (locale.toLowerCase().startsWith("id")) {
      return "id";
    }
    return "en";
  } catch {
    return "id";
  }
}

